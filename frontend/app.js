const languageSelect = document.querySelector("#language");
const profileForm = document.querySelector("#profile-form");
const resultsSection = document.querySelector("#results");
const assistantForm = document.querySelector("#assistant-form");
const cropForm = document.querySelector("#crop-form");
let currentLanguage = "en";

function text(key) {
  return translations[currentLanguage][key] || translations.en[key] || key;
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[character]);
}

function translatePage() {
  currentLanguage = languageSelect.value;
  document.documentElement.lang = currentLanguage === "ta" ? "ta" : "en";
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (translations[currentLanguage][key]) element.textContent = translations[currentLanguage][key];
  });
  if (assistantForm.elements.message.placeholder === "Type your question..." ||
      ["Type your question...", "உங்கள் கேள்வியை உள்ளிடவும்", "Unga kelviyai type pannunga..."].includes(assistantForm.elements.message.placeholder)) {
    assistantForm.elements.message.placeholder = currentLanguage === "ta"
      ? "உங்கள் கேள்வியை உள்ளிடவும்"
      : currentLanguage === "tanglish" ? "Unga kelviyai type pannunga..." : "Type your question...";
  }
}

function profileFromForm() {
  const values = Object.fromEntries(new FormData(profileForm).entries());
  return values;
}

async function postJson(url, body) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body)
  });
  const result = await response.json();
  if (!response.ok) throw new Error(result.error || `HTTP ${response.status}`);
  return result;
}

function showError(container, error) {
  container.className = "error-state";
  container.textContent = `${text("errorPrefix")} ${error.message}`;
}

function renderMatches(data, heading = text("matches")) {
  resultsSection.replaceChildren();
  const title = document.createElement("div");
  title.className = "results-heading";
  title.innerHTML = `<h2>${escapeHtml(heading)}</h2><span class="result-count">${data.matches.length} ${currentLanguage === "en" ? "found" : ""}</span>`;
  resultsSection.append(title);

  if (!data.matches.length) {
    const empty = document.createElement("div");
    empty.className = "empty-state";
    empty.textContent = data.schemes && !data.schemes.length ? text("matchEmpty") : text("none");
    resultsSection.append(empty);
    return;
  }

  const list = document.createElement("div");
  list.className = "scheme-list";
  for (const item of data.matches) {
    const scheme = item.scheme;
    const card = document.createElement("article");
    card.className = "scheme-card";
    const reasons = [...item.reasons, ...item.mismatches];
    const reasonItems = reasons.map(reason => `<li>${escapeHtml(reason)}</li>`).join("");
    const documentText = item.documents_note || text("documentsUnverified");
    const officialLink = /^https:\/\/[a-z0-9.-]+(?:\/|$)/i.test(scheme.source_url)
      ? `<a class="scheme-link" href="${escapeHtml(scheme.source_url)}" target="_blank" rel="noopener noreferrer">${escapeHtml(text("officeReminder"))} ↗</a>`
      : "";
    card.innerHTML = `
      <div class="scheme-card-top">
        <div><h3>${escapeHtml(scheme.name)}</h3><div class="scheme-level">${escapeHtml(scheme.level)} · ${escapeHtml(scheme.states.join(", "))}</div></div>
        <span class="status-badge">${escapeHtml(text("potential"))}</span>
      </div>
      <p class="scheme-summary">${escapeHtml(scheme.summary)}</p>
      <div class="small-note">${escapeHtml(text("whyRelevant"))}</div>
      <ul class="scheme-details">${reasonItems}</ul>
      <div class="document-note"><strong>${escapeHtml(text("eligibilityNotAssessed"))}.</strong> ${escapeHtml(item.eligibility_note || "")}</div>
      <div class="document-note">${escapeHtml(scheme.eligibility_notes)}</div>
      <div class="document-note"><strong>${escapeHtml(text("documentsUnverified"))}.</strong> ${escapeHtml(documentText)}</div>
      <div class="small-note"><strong>${escapeHtml(text("nextAction"))}:</strong> ${escapeHtml(item.next_action)}</div>
      ${officialLink}`;
    list.append(card);
  }
  resultsSection.append(list);
  if (data.disclaimer) {
    const disclaimer = document.createElement("p");
    disclaimer.className = "disclaimer";
    disclaimer.textContent = data.disclaimer;
    resultsSection.append(disclaimer);
  }
}

profileForm.addEventListener("submit", async event => {
  event.preventDefault();
  const button = profileForm.querySelector("button[type=submit]");
  button.disabled = true;
  resultsSection.innerHTML = `<div class="empty-state">${escapeHtml(text("loading"))}</div>`;
  try {
    const data = await postJson("/api/match", profileFromForm());
    renderMatches(data);
    resultsSection.scrollIntoView({ behavior: "smooth", block: "start" });
  } catch (error) {
    resultsSection.replaceChildren();
    const message = document.createElement("div");
    showError(message, error);
    resultsSection.append(message);
  } finally {
    button.disabled = false;
  }
});

assistantForm.addEventListener("submit", async event => {
  event.preventDefault();
  const button = assistantForm.querySelector("button[type=submit]");
  const resultBox = document.querySelector("#assistant-result");
  button.disabled = true;
  resultBox.className = "tool-result visible";
  resultBox.textContent = text("loading");
  try {
    const result = await postJson("/api/assistant", {
      message: assistantForm.elements.message.value,
      profile: profileFromForm(),
      language: currentLanguage
    });
    resultBox.textContent = `${result.answer} ${result.disclaimer}`;
    if (result.matches.length) renderMatches({ matches: result.matches, disclaimer: result.disclaimer }, text("assistantDone"));
  } catch (error) {
    resultBox.textContent = `${text("errorPrefix")} ${error.message}`;
  } finally {
    button.disabled = false;
  }
});

cropForm.addEventListener("submit", async event => {
  event.preventDefault();
  const button = cropForm.querySelector("button[type=submit]");
  const resultBox = document.querySelector("#crop-result");
  button.disabled = true;
  resultBox.className = "tool-result visible";
  resultBox.textContent = text("loading");
  try {
    const values = Object.fromEntries(new FormData(cropForm).entries());
    const result = await postJson("/api/crop-recommendation", values);
    const alternatives = result.alternatives.length
      ? ` ${text("cropAlternatives")}: ${result.alternatives.join(", ")}.`
      : "";
    resultBox.innerHTML = `<strong>${escapeHtml(text("cropResult"))}: ${escapeHtml(result.recommendation)}</strong><br>${escapeHtml(text("confidence"))}: ${Math.round(result.confidence * 100)}%.${escapeHtml(alternatives)}<br><span class="small-note">${escapeHtml(result.disclaimer)}</span>`;
  } catch (error) {
    resultBox.textContent = `${text("errorPrefix")} ${error.message}`;
  } finally {
    button.disabled = false;
  }
});

